// Turns the Power BI export (data.csv), the raw Kpler trades table and the Natural Earth TopoJSON
// files into plain <script> files, because a page opened from disk (file://) can't fetch() JSON.
//
//   node build-data.mjs flows <data.csv> <out.js>
//   node build-data.mjs kpler <trades.csv> <locations.csv> <out.js> <id> "<title>" [originCountries|*] [year] [top]
//   node build-data.mjs wrap  <in.json>  <out.js> <GLOBAL_NAME>
import { readFileSync, writeFileSync } from 'node:fs';

const [mode, input, output, globalName] = process.argv.slice(2);

// Every sample registers itself here; the mockup offers them in its "Sample" control.
const registerSample = (id, sample) =>
  'window.SAMPLES = window.SAMPLES || {};\nwindow.SAMPLES[' + JSON.stringify(id) + '] = ' + JSON.stringify(sample) + ';\n';

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    }
    else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some(v => v !== '')) rows.push(row);
      row = [];
    }
    else field += c;
  }
  row.push(field);
  if (row.some(v => v !== '')) rows.push(row);
  return rows;
}

function parseLatLon(text) {
  const parts = String(text).split(',').map(s => parseFloat(s.trim()));
  const [lat, lon] = parts;
  const ok = parts.length === 2 && isFinite(lat) && isFinite(lon) && Math.abs(lat) <= 90 && Math.abs(lon) <= 180;
  return ok ? [lat, lon] : null;
}

if (mode === 'flows') {
  const [header, ...body] = parseCsv(readFileSync(input, 'utf8').replace(/^﻿/, ''));
  // The export repeats the "LatLon" header, so roles are found by position among matches.
  const find = re => header.map((h, i) => re.test(h) ? i : -1).filter(i => i >= 0);
  const vol = find(/volume/i)[0];
  const [oLL, dLL] = find(/lat/i);
  const oName = find(/\(origin\)/i)[0], dName = find(/\(destination\)/i)[0];
  if ([vol, oLL, dLL, oName, dName].some(i => i === undefined)) {
    throw new Error('Could not find volume / LatLon / origin / destination columns in: ' + header.join(' | '));
  }
  const rows = [], skipped = [];
  for (const r of body) {
    const v = parseFloat(String(r[vol]).replace(/,/g, ''));
    const o = parseLatLon(r[oLL]), d = parseLatLon(r[dLL]);
    if (!isFinite(v) || !o || !d) { skipped.push(r); continue; }
    rows.push([v, o[0], o[1], d[0], d[1], r[oName], r[dName]]);
  }
  const total = rows.reduce((s, r) => s + r[0], 0);
  const out = {
    title: 'Caribbean (dashboard export)',
    source: input.split(/[\\/]/).pop(),
    columns: ['volume', 'oLat', 'oLon', 'dLat', 'dLon', 'oLabel', 'dLabel'],
    unit: (header[vol].match(/\(([^)]+)\)/) || [, ''])[1],
    rows,
    skipped: skipped.length,
    skippedVolume: skipped.reduce((s, r) => s + (parseFloat(String(r[vol]).replace(/,/g, '')) || 0), 0)
  };
  writeFileSync(output, '// Generated by tools/build-data.mjs from ' + out.source + ' - do not commit (licensed data).\n'
    + registerSample('caribbean', out));
  console.log(`flows: ${rows.length} rows, ${skipped.length} skipped, total ${total.toLocaleString('en-US')} ${out.unit}`);
  console.log(`origins: ${new Set(rows.map(r => r[5])).size}, destinations: ${new Set(rows.map(r => r[6])).size}`);
}
else if (mode === 'kpler') {
  // Aggregates the raw trades table (';'-separated, as the API returns it) into routes, joined to
  // the coordinates exported from the model's LocDim tables. Location keys follow the model's M:
  // "Installation, Zone, Country" with blanks as "Non-Disclosed" and "Non-Disclosed, " removed.
  const [, , , , locPath, out, id, title, originArg = '*', yearArg = '', topArg = '400'] = process.argv;
  const lines = readFileSync(input, 'utf8').replace(/^﻿/, '').split(/\r?\n/).filter(Boolean);
  const H = lines[0].split(';'), C = Object.fromEntries(H.map((h, i) => [h, i]));
  const nd = v => v === '' ? 'Non-Disclosed' : v;
  const key = (i, z, c) => [nd(i), nd(z), nd(c)].join(', ').split('Non-Disclosed, ').join('');

  const [lh, ...locs] = parseCsv(readFileSync(locPath, 'utf8').replace(/^﻿/, ''));
  const L = Object.fromEntries(lh.map((h, i) => [h, i]));
  const exact = new Map(), byZone = new Map();
  for (const r of locs) {
    const lat = parseFloat(r[L.lat]), lon = parseFloat(r[L.lon]);
    if (!isFinite(lat) || !isFinite(lon)) continue;
    exact.set(r[L.key], [lat, lon]);
    const zk = r[L.zone] + '|' + r[L.country];
    if (!byZone.has(zk)) byZone.set(zk, [lat, lon]);
  }
  // Exact location, else another installation in the same zone (flagged approximate), else nothing.
  const locate = (i, z, c) => exact.get(key(i, z, c)) || (byZone.has(nd(z) + '|' + nd(c)) ? [...byZone.get(nd(z) + '|' + nd(c)), 1] : null);

  const origins = originArg === '*' ? null : new Set(originArg.split(','));
  const routes = new Map();
  let filtered = 0, unmapped = 0, unmappedVol = 0;
  for (const l of lines.slice(1)) {
    const r = l.split(';');
    if (origins && !origins.has(r[C['Country (origin)']])) continue;
    if (yearArg && !(r[C['Date (origin)']] || '').startsWith(yearArg)) continue;
    const v = +r[C['Volume (bbl)']] || 0;
    filtered += v;
    const oi = [r[C['Installation origin']], r[C['Zone Origin']], r[C['Country (origin)']]];
    const di = [r[C['Installation Destination']], r[C['Zone Destination']], r[C['Country (destination)']]];
    const o = locate(...oi), d = locate(...di);
    if (!o || !d) { unmapped++; unmappedVol += v; continue; }
    const canal = r[C['Zone Canal Transit']];
    const k = key(...oi) + '>' + key(...di) + '>' + canal;
    let route = routes.get(k);
    if (!route) routes.set(k, route = { v: 0, n: 0, o, d, oLabel: key(...oi), dLabel: key(...di), canal });
    route.v += v;
    route.n++;
  }
  const sorted = [...routes.values()].sort((a, b) => b.v - a.v);
  const kept = sorted.slice(0, +topArg);
  const keptVol = kept.reduce((s, r) => s + r.v, 0);
  const sample = {
    title, source: input.split(/[\\/]/).pop(),
    columns: ['volume', 'oLat', 'oLon', 'dLat', 'dLon', 'oLabel', 'dLabel', 'canal', 'approx', 'trades'],
    unit: 'bbls',
    rows: kept.map(r => [r.v, r.o[0], r.o[1], r.d[0], r.d[1], r.oLabel, r.dLabel, r.canal, (r.o[2] ? 1 : 0) | (r.d[2] ? 2 : 0), r.n]),
    skipped: unmapped + (sorted.length - kept.length),
    skippedVolume: unmappedVol + (filtered - unmappedVol - keptVol)
  };
  writeFileSync(out, '// Generated by tools/build-data.mjs from ' + sample.source + ' - do not commit (licensed Kpler data).\n'
    + registerSample(id, sample));
  const pct = x => (100 * x / filtered).toFixed(1) + '%';
  console.log(`${id}: ${filtered.toLocaleString('en-US')} bbl in filter; ${sorted.length} routes, kept top ${kept.length} = ${pct(keptVol)}; unmapped ${pct(unmappedVol)}`);
  console.log(`origins ${new Set(kept.map(r => r.oLabel)).size}, destinations ${new Set(kept.map(r => r.dLabel)).size}, approximate-location routes ${kept.filter(r => r.o[2] || r.d[2]).length}`);
}
else if (mode === 'wrap') {
  const json = JSON.parse(readFileSync(input, 'utf8'));
  writeFileSync(output, 'window.' + globalName + ' = ' + JSON.stringify(json) + ';\n');
  console.log(`wrapped ${input.split(/[\\/]/).pop()} -> ${globalName}`);
}
else {
  console.error('usage: node build-data.mjs flows <csv> <out.js> | wrap <json> <out.js> <GLOBAL>');
  process.exit(1);
}
